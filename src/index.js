function updateClock() {
  let clockTimeElement = document.querySelector("#clock-time");
  let clockContainer = document.querySelector("#live-clock");
  if (!clockTimeElement) return;

  let now = new Date();
  let hours = now.getHours();
  let minutes = now.getMinutes();
  let seconds = now.getSeconds();
  let ampm = hours >= 12 ? "PM" : "AM";
  hours = hours % 12;
  hours = hours ? hours : 12;

  let formattedMinutes = minutes < 10 ? `0${minutes}` : minutes;
  let formattedSeconds = seconds < 10 ? `0${seconds}` : seconds;

  clockTimeElement.innerHTML = `${hours}:${formattedMinutes}:${formattedSeconds} ${ampm}`;

  if (clockContainer) {
    let locale =
      (translations[currentLanguage] &&
        translations[currentLanguage].locale) ||
      "en-US";
    clockContainer.title = now.toLocaleDateString(locale, {
      weekday: "long",
      year: "numeric",
      month: "short",
      day: "numeric",
    });
  }
}

function initClock() {
  let clockContainer = document.querySelector("#live-clock");
  let clockToggleBtn = document.querySelector("#clock-toggle-btn");
  let clockCloseBtn = document.querySelector("#clock-close-btn");

  if (clockToggleBtn && clockContainer) {
    clockToggleBtn.addEventListener("click", function (event) {
      event.stopPropagation();
      clockContainer.classList.toggle("collapsed");
      let isCollapsed = clockContainer.classList.contains("collapsed");
      let t = translations[currentLanguage] || translations.en;
      clockToggleBtn.title = isCollapsed ? t.clockOpen : t.clockClose;
    });
  }

  if (clockCloseBtn && clockContainer) {
    clockCloseBtn.addEventListener("click", function (event) {
      event.stopPropagation();
      clockContainer.classList.add("collapsed");
      if (clockToggleBtn) {
        let t = translations[currentLanguage] || translations.en;
        clockToggleBtn.title = t.clockOpen;
      }
    });
  }

  if (clockContainer) {
    clockContainer.addEventListener("click", function () {
      if (clockContainer.classList.contains("collapsed")) {
        clockContainer.classList.remove("collapsed");
        let t = translations[currentLanguage] || translations.en;
        if (clockToggleBtn) {
          clockToggleBtn.title = t.clockClose;
        }
      }
    });
  }
}

