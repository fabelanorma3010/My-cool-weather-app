let currentLanguage = localStorage.getItem("weather_app_lang") || "en";
let currentUnit = localStorage.getItem("weather_app_unit") || "celsius";
let currentTemperatureCelsius = null;
let lastWeatherResponse = null;
let lastForecastResponse = null;

function celsiusToFahrenheit(celsius) {
  return (celsius * 9) / 5 + 32;
}

function formatTemperature(celsius) {
  if (celsius === null || celsius === undefined || isNaN(celsius)) return "";
  if (currentUnit === "fahrenheit") {
    return Math.round(celsiusToFahrenheit(celsius));
  }
  return Math.round(celsius);
}

function updateTemperatureDisplay() {
  let temperatureElement = document.querySelector("#temperature");
  if (temperatureElement && currentTemperatureCelsius !== null) {
    temperatureElement.innerHTML = formatTemperature(currentTemperatureCelsius);
  }

  let celsiusLink = document.querySelector("#celsius-link");
  let fahrenheitLink = document.querySelector("#fahrenheit-link");
  if (celsiusLink && fahrenheitLink) {
    if (currentUnit === "celsius") {
      celsiusLink.classList.add("active");
      fahrenheitLink.classList.remove("active");
    } else {
      fahrenheitLink.classList.add("active");
      celsiusLink.classList.remove("active");
    }
  }

  if (lastForecastResponse) {
    displayForecast(lastForecastResponse);
  }
}

function handleCelsiusClick(event) {
  if (event) event.preventDefault();
  if (currentUnit === "celsius") return;
  currentUnit = "celsius";
  localStorage.setItem("weather_app_unit", "celsius");
  updateTemperatureDisplay();
}

function handleFahrenheitClick(event) {
  if (event) event.preventDefault();
  if (currentUnit === "fahrenheit") return;
  currentUnit = "fahrenheit";
  localStorage.setItem("weather_app_unit", "fahrenheit");
  updateTemperatureDisplay();
}

